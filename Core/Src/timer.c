#include "timer.h"

TIM_HandleTypeDef htim3;
TIM_HandleTypeDef htim4;
TIM_HandleTypeDef htim8;

/* TIM3: 96 MHz / (96 * 1000) = 1000 Hz → Overflow alle 1 ms */
